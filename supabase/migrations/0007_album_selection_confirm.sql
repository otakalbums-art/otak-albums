-- ============================================================================
-- Підтвердження самостійного відбору фото для альбому
-- ============================================================================
-- Учень тепер формує фото для альбому напряму в CRM-слоти (student_slot_photos,
-- ті самі, якими керує адмін) — обмежений вибором лише зі своїх favorites.
-- Це поле фіксує момент, коли учень явно натиснув "Підтвердити відбір";
-- будь-яка подальша зміна слота (учнем чи адміном) скидає його в null.
-- Старий плаский "album_selections" (і /api/photos/[id]/select,
-- /api/album-selection/confirm) — застарілий, замінюється цим підходом;
-- саму таблицю не видаляємо, просто перестаємо на неї посилатись з коду.
-- ============================================================================

alter table students add column selection_confirmed_at timestamptz;
comment on column students.selection_confirmed_at is
  'Коли учень востаннє підтвердив відбір фото для альбому (student_slot_photos) — будь-яка подальша зміна слота (учнем чи адміном) скидає це поле в null, доки не підтвердить(ять) знову.';
